const SEED_CREATED_AT = new Date('2024-01-01T00:00:00.000Z');

// Deterministic UUIDs from non-determinism.ts always match this prefix pattern.
// We assert the pattern (not the exact counter value) because the counter's starting
// position within a scenario depends on execution order and shared scenario IDs.
const DETERMINISTIC_UUID_RE = /^00000000-0000-4000-8000-[0-9a-f]{12}$/;

// Mirror of fake-fetch's HTTP_REASON table — used to compute expected error_message values
// in delivery log assertions for HTTP-error exhaustion scenarios.
const HTTP_REASON: Record<number, string> = {
  200: 'OK', 201: 'Created', 204: 'No Content',
  400: 'Bad Request', 401: 'Unauthorized', 403: 'Forbidden',
  404: 'Not Found', 409: 'Conflict', 422: 'Unprocessable Entity',
  429: 'Too Many Requests',
  500: 'Internal Server Error', 502: 'Bad Gateway', 503: 'Service Unavailable',
};

// Network-error message the "unreachable" Given steps throw via fail(); deliver.ts logs it verbatim as
// the delivery_log error_message, which scenarios pin as an expected literal. Kept a stable constant so
// the assertion isn't a tautology reading the value back out of the captured log (hardcoded-expected-values).
const NETWORK_FAILURE_ERROR = '[fake-fetch] Injected network failure (configured via fail)';

